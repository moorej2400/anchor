#!/usr/bin/env node
/**
 * Build the browser mock from Anchor's real React entry point.
 *
 * The output is one self-contained HTML file so it can be opened directly
 * from docs/ without Vite, Tauri, or a local server. VITE_IPC=mock keeps all
 * runtime state synthetic while the components, styles, icons, and behavior
 * remain the same code used by the desktop application.
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import react from "@vitejs/plugin-react";
import { build } from "vite";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const repoRoot = join(scriptDir, "..", "..");
const outputPath = join(repoRoot, "docs", "Anchor-Implementation-Mock.html");

function escapeInlineBlock(source, tag) {
  return source
    .replace(new RegExp(`</${tag}`, "gi"), `<\\/${tag}`)
    .replace(/[ \t]+$/gm, "");
}

function escapeInlineJavascript(source) {
  return escapeInlineBlock(source, "script")
    // In an HTML script raw-text block, a literal `<script` inside a JavaScript
    // string enters the parser's double-escaped state. The real closing tag is
    // then ignored, so the bundle never executes and the boot message remains.
    .replace(/<script/gi, (match) => `\\x3C${match.slice(1)}`)
    .replace(/<!--/g, "\\x3C!--");
}

export function renderStandaloneHtml(css, javascript) {
  const safeCss = escapeInlineBlock(css, "style");
  const safeJavascript = escapeInlineJavascript(javascript);

  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="anchor-preview" content="generated-from-real-frontend" />
    <title>Anchor — implementation mock</title>
    <!-- Generated by npm run mock:build. Edit src/, not this file. -->
    <style>
      html, body, #root { height: 100%; margin: 0; }
      body { background: #0b0b11; color: rgba(255, 255, 255, 0.9); }
      #preview-boot { height: 100%; display: grid; place-items: center; font: 13px system-ui, sans-serif; }
      #preview-error { max-width: 640px; padding: 24px; color: #f0757f; white-space: pre-wrap; }
${safeCss}
    </style>
  </head>
  <body>
    <div id="root"><div id="preview-boot">Starting Anchor preview…</div></div>
    <script>
      window.addEventListener("error", function (event) {
        var root = document.getElementById("root");
        if (root) root.innerHTML = '<pre id="preview-error"></pre>';
        var error = document.getElementById("preview-error");
        if (error) error.textContent = "Anchor preview failed to start\\n\\n" + String(event.message || event.error || "Unknown error");
      });
    </script>
    <script>${safeJavascript}</script>
  </body>
</html>
`;
}

function bundleParts(result) {
  const outputs = Array.isArray(result) ? result.flatMap((item) => item.output) : result.output;
  const chunks = outputs.filter((item) => item.type === "chunk" && item.isEntry);
  const cssAssets = outputs.filter(
    (item) => item.type === "asset" && typeof item.fileName === "string" && item.fileName.endsWith(".css"),
  );
  const unsupported = outputs.filter(
    (item) => item.type === "asset" && !String(item.fileName).endsWith(".css"),
  );

  if (chunks.length !== 1 || cssAssets.length !== 1 || unsupported.length > 0) {
    const names = outputs.map((item) => `${item.type}:${item.fileName}`).join(", ");
    throw new Error(`Expected one inline script and one inline stylesheet; received ${names}`);
  }

  const css = typeof cssAssets[0].source === "string"
    ? cssAssets[0].source
    : Buffer.from(cssAssets[0].source).toString("utf8");
  return { css, javascript: chunks[0].code };
}

export async function buildImplementationMock() {
  const result = await build({
    configFile: false,
    root: repoRoot,
    mode: "production",
    logLevel: "warn",
    plugins: [react()],
    define: {
      "import.meta.env.VITE_IPC": JSON.stringify("mock"),
      // Vite library builds leave Node environment checks in React otherwise.
      "process.env.NODE_ENV": JSON.stringify("production"),
    },
    build: {
      write: false,
      sourcemap: false,
      minify: "esbuild",
      cssCodeSplit: false,
      assetsInlineLimit: Number.MAX_SAFE_INTEGER,
      lib: {
        entry: join(repoRoot, "src", "main.tsx"),
        name: "AnchorImplementationMock",
        formats: ["iife"],
        fileName: () => "anchor-implementation-mock.js",
      },
      rollupOptions: {
        output: {
          inlineDynamicImports: true,
          assetFileNames: "anchor-implementation-mock[extname]",
        },
      },
    },
  });

  const { css, javascript } = bundleParts(result);
  return renderStandaloneHtml(css, javascript);
}

async function main() {
  const html = await buildImplementationMock();
  if (process.argv.includes("--check")) {
    const current = await readFile(outputPath, "utf8").catch(() => "");
    if (current !== html) {
      throw new Error("docs/Anchor-Implementation-Mock.html is stale. Run npm run mock:build.");
    }
    console.log("Implementation mock matches the real frontend.");
    return;
  }

  await writeFile(outputPath, html, "utf8");
  console.log(`Built ${outputPath}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  main().catch((error) => {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  });
}
